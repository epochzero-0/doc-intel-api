"""Where uploaded files live: an S3 bucket when S3_BUCKET is set, else a local directory.

Keys are "<user_id>/<uuid><ext>", generated by the upload endpoint. The client's
filename never becomes part of a key.
"""
import os
import shutil
import tempfile
from contextlib import contextmanager
from typing import BinaryIO, Iterator

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


class LocalStorage:
    def __init__(self, root: str):
        self.root = root
        os.makedirs(root, exist_ok=True)

    def _path(self, key: str) -> str:
        return os.path.join(self.root, key)

    def save(self, key: str, fileobj: BinaryIO) -> None:
        path = self._path(key)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as out:
            shutil.copyfileobj(fileobj, out)

    @contextmanager
    def local_copy(self, key: str) -> Iterator[str]:
        yield self._path(key)

    def delete(self, key: str) -> None:
        path = self._path(key)
        if os.path.exists(path):
            os.remove(path)


class S3Storage:
    PREFIX = "uploads/"

    def __init__(self, bucket: str):
        import boto3

        self.bucket = bucket
        self.s3 = boto3.client("s3")

    def save(self, key: str, fileobj: BinaryIO) -> None:
        self.s3.upload_fileobj(fileobj, self.bucket, self.PREFIX + key)

    @contextmanager
    def local_copy(self, key: str) -> Iterator[str]:
        # The parser needs a path with the right extension, so download to a temp file.
        fd, path = tempfile.mkstemp(suffix=os.path.splitext(key)[1])
        os.close(fd)
        try:
            self.s3.download_file(self.bucket, self.PREFIX + key, path)
            yield path
        finally:
            os.remove(path)

    def delete(self, key: str) -> None:
        self.s3.delete_object(Bucket=self.bucket, Key=self.PREFIX + key)


def make_storage():
    bucket = os.getenv("S3_BUCKET")
    if bucket:
        return S3Storage(bucket)
    return LocalStorage(os.getenv("UPLOAD_DIR", os.path.join(PROJECT_ROOT, "uploads")))
